import http.client, json
conn = http.client.HTTPConnection("localhost", 8000, timeout=10)
body = json.dumps({"family_id": "807325", "member_name": "我"})
conn.request("POST", "/api/auth/login", body, {"Content-Type": "application/json"})
resp = conn.getresponse()
data = resp.read()
print(f"Status: {resp.status}")
print(f"Body (raw): {data}")
print(f"Body (repr): {repr(data)}")
conn.close()
